import { createBoardLinkEditorController } from "./board-link-editor-controller.js";
import { createBoardLinkHighlightController } from "./board-link-highlight-controller.js";
import { createBoardLinkInteractionController } from "./board-link-interaction-controller.js";
import { createBoardLinkPopupController } from "./board-link-popup-controller.js";
import { createBoardLinkRenderController } from "./board-link-render-controller.js";
import { createBoardLinkTextController } from "./board-link-text-controller.js";
import { createBoardSelectionVisualController } from "./board-selection-visual-controller.js";

export function createBoardLinkStack({
  documentRef,
  getCtx,
  getBoardItems,
  getBoardLinks,
  setBoardLinks,
  getBoardSettings,
  getBoardStrokes,
  getCurrentTool,
  getItemElements,
  getItemSelectionLayer,
  getStage,
  getViewPan,
  getZoom,
  getLinksSvg,
  getSelectedLinkId,
  setSelectedLinkId,
  getSelectedItemIds,
  clearSelectedItemIds,
  getSelectedShapeIds,
  resetSelectedShapeIds,
  setShapeSelectionFromShift,
  getLinkEditingId,
  setLinkEditingId,
  getLinkEditor,
  getLinkControls,
  getLinkColorOptions,
  getLinkStyleOptions,
  getLinkPreviewLine,
  setLinkPreviewLine,
  getLinkPreviewPoint,
  setLinkPreviewPoint,
  getLinkSource,
  setLinkSource,
  getLinkHoverTarget,
  setLinkHoverTarget,
  getLinkDragActive,
  setLinkDragActive,
  getLinkUpdateRaf,
  setLinkUpdateRaf,
  getLastLinkClickId,
  setLastLinkClickId,
  getLastLinkClickTime,
  setLastLinkClickTime,
  getLinkControlsRefs,
  createLinkId,
  getWorldPointFromClient,
  findLinkableShapeAtPoint,
  boardCanvasRenderApi,
  boardPersistenceApi,
  boardShellApi,
  boardLinkPopupApi,
  boardLinkControlsSetupApi,
  boardUiPreview,
  boardShapeRendererApi,
  boardCanvasQueryApi,
  drawSelectionOutline,
  updateItemSelectionStyles,
  getEndpointDataFromEndpoint,
  getLinkEndpointData,
  getLinkAnchorPoint,
  getLinkGapForEndpoint,
  getOffsetLinkPoint,
  getLinkEditorLayout,
  isSameLinkEndpoint,
  isLinkBetweenEndpoints,
  makeLinkEndpoint,
  linkDoubleClickDelay,
  linkGap,
  linkStyleDashDot,
  linkStyleDashed,
  linkStyleDotted,
  linkStyleSolid,
  linkTypeItem,
  linkTypeShape,
  selectionDash,
  selectionRadius,
  toolLink,
  toolSelect,
}) {
  let boardLinkRender;
  let boardSelectionVisual;
  let boardLinkEditor;

  const boardLinkHighlight = createBoardLinkHighlightController({
    getBoardItems,
    getItemElements,
    getItemSelectionLayer,
  });

  const boardLinkInteraction = createBoardLinkInteractionController({
    createLinkId,
    getBoardLinks,
    getCurrentTool,
    getLinkDragActive,
    getLinkHoverTarget,
    getLinkPreviewPoint,
    getLinkSource,
    getStage,
    setLinkDragActive,
    setLinkHoverTarget,
    setLinkPreviewPoint,
    setLinkSource,
    clearLinkItemHighlight: boardLinkHighlight.clearLinkItemHighlight,
    updateLinkItemHighlight: boardLinkHighlight.updateLinkItemHighlight,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    getWorldPointFromClient,
    updateLinkPreviewFromState: (...args) =>
      boardLinkRender.updateLinkPreviewFromState(...args),
    clearLinkPreviewLine: (...args) =>
      boardLinkRender.clearLinkPreviewLine(...args),
    updateLinks: (...args) => boardLinkRender.updateLinks(...args),
    scheduleSave: boardPersistenceApi.scheduleSave,
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    makeLinkEndpoint,
    findLinkableShapeAtPoint,
    isSameLinkEndpoint,
    isLinkBetweenEndpoints,
    linkTypeItem,
    linkTypeShape,
    toolLink,
  });

  const boardLinkPopup = createBoardLinkPopupController({
    getBoardZoom: getZoom,
    getLinkControls,
    getLinkRenderPoints: (...args) => boardLinkRender.getLinkRenderPoints(...args),
    getLinkSelectionBounds: (...args) =>
      boardSelectionVisual.getLinkSelectionBounds(...args),
    getSelectedLink: () => boardLinkRender.getSelectedLink(),
    getSelectedLinkId,
    getStage,
    getViewPan,
    clearLinkSelection: boardLinkInteraction.clearLinkSelection,
    clearOtherSelections: () => {
      if (!getSelectedShapeIds().size && !getSelectedItemIds().size) return;
      resetSelectedShapeIds();
      clearSelectedItemIds();
      setShapeSelectionFromShift(false);
      updateItemSelectionStyles();
    },
    closeLinkMenus: boardLinkControlsSetupApi.closeLinkMenus,
    hideLinkControls: boardLinkPopupApi.hideLinkControls,
    isLinkingModeActive: boardLinkInteraction.isLinkingModeActive,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    scheduleLinkUpdate: (...args) => boardLinkRender.scheduleLinkUpdate(...args),
    setSelectedLinkId,
    showLinkControls: boardLinkPopupApi.showLinkControls,
    syncLinkControls: () => boardLinkRender.syncLinkControls(),
  });

  const boardLinkText = createBoardLinkTextController({
    getCtx,
    getDefaultTextSize: () => getBoardSettings().textSize,
    getLinkDefaultColor: () => boardSelectionVisual.getLinkSelectionColor(),
    getLinkEditingId,
    getLinkEditor,
    getShapeFontFamily: () => boardShapeRendererApi.getShapeFontFamily(),
    getWrapTextLines: () => boardShapeRendererApi.wrapShapeTextLines,
    getZoom,
    linkGap,
  });

  boardSelectionVisual = createBoardSelectionVisualController({
    documentRef,
    drawSelectionOutline,
    getBoardLinks,
    getCtx,
    getLinkEditingId,
    getLinkEditorBounds: (...args) => boardLinkText.getLinkEditorBounds(...args),
    getLinkLabelBounds: (...args) => boardLinkText.getLinkLabelBounds(...args),
    getLinkRenderPoints: (...args) => boardLinkRender.getLinkRenderPoints(...args),
    getSelectedLinkId,
    getShapeHitPadding: boardCanvasQueryApi.getShapeHitPadding,
    getStage,
    selectionDash,
    selectionRadius,
  });

  boardLinkEditor = createBoardLinkEditorController({
    getBoardLinks,
    getCtx,
    getDefaultTextSize: () => getBoardSettings().textSize,
    getFontFamily: () => boardShapeRendererApi.getShapeFontFamily(),
    getLinkEditor,
    getLinkEditingId,
    getLinkRenderPoints: (...args) => boardLinkRender.getLinkRenderPoints(...args),
    getLinkTextColor: (...args) => boardLinkText.getLinkTextColor(...args),
    getStage,
    getWrapTextLines: () => boardShapeRendererApi.wrapShapeTextLines,
    setLinkEditingId,
    getLinkEditorLayout,
    linkGap,
    positionLinkEditorFromPointsRef: (...args) =>
      boardLinkEditor.positionLinkEditorFromPoints(...args),
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    scheduleHistoryCommit: boardShellApi.scheduleHistoryCommit,
    scheduleSave: boardPersistenceApi.scheduleSave,
    updateLinks: (...args) => boardLinkRender.updateLinks(...args),
  });

  boardLinkRender = createBoardLinkRenderController({
    clearLinkPopup: boardLinkPopup.clearLinkPopup,
    closeLinkEditor: boardLinkEditor.closeLinkEditor,
    createLinkLabelElement: (...args) => boardLinkText.createLinkLabelElement(...args),
    getBoardItems,
    getBoardLinks,
    getBoardStrokes,
    getCurrentTool,
    getEndpointDataFromEndpoint,
    getLinkEndpointData,
    getLinkHoverTarget,
    getItemElements,
    getLastLinkClickId,
    getLastLinkClickTime,
    getLinkAnchorPoint,
    getLinkColorOptions,
    getLinkControlsRefs,
    getLinkDefaultColor: () => boardSelectionVisual.getLinkSelectionColor(),
    getLinkEditingId,
    getLinkGapForEndpoint,
    getLinkPreviewLine,
    getLinkPreviewPoint,
    getLinkSource,
    getLinkStyleOptions,
    getLinkUpdateRaf,
    getLinksSvg,
    getOffsetLinkPoint,
    getSelectedLinkId,
    getStage,
    getViewPan,
    getZoom,
    hideLinkControls: boardLinkPopupApi.hideLinkControls,
    isSameLinkEndpoint,
    linkDoubleClickDelay,
    linkStyleDashDot,
    linkStyleDashed,
    linkStyleDotted,
    linkStyleSolid,
    linkTool: toolLink,
    positionLinkControls: boardLinkPopup.positionLinkControls,
    positionLinkEditorFromPoints: (...args) =>
      boardLinkEditor.positionLinkEditorFromPoints(...args),
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    scheduleHistoryCommit: boardShellApi.scheduleHistoryCommit,
    scheduleSave: boardPersistenceApi.scheduleSave,
    selectLink: boardLinkPopup.selectLink,
    setBoardLinks,
    setLastLinkClickId,
    setLastLinkClickTime,
    setLinkPreviewLine,
    setLinkUpdateRaf,
    setSelectedLinkId,
    showLinkControls: boardLinkPopupApi.showLinkControls,
    startLinkTextEditing: boardLinkEditor.startLinkTextEditing,
    syncShapeColorMenu: boardUiPreview.syncShapeColorMenu,
    setShapeColorButtonSwatch: boardUiPreview.setShapeColorButtonSwatch,
    toolSelect,
  });

  return {
    boardLinkEditor,
    boardLinkHighlight,
    boardLinkInteraction,
    boardLinkPopup,
    boardLinkRender,
    boardLinkText,
    boardSelectionVisual,
  };
}
