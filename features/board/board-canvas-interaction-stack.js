export function createBoardCanvasInteractionStack({
  documentRef,
  windowRef,
  getText,
  createId,
  getCurrentTool,
  getBoardSettings,
  getBoardStrokes,
  getCanvas,
  getCtx,
  getStage,
  getLinksSvg,
  getViewportController,
  getSelectedItemIds,
  getSelectedShapeIds,
  getShapeEditingId,
  getActiveShape,
  setActiveShape,
  getActiveStroke,
  setActiveStroke,
  getDrawing,
  setDrawing,
  getDraggingMixed,
  getDraggingShape,
  getIsMarqueeSelecting,
  getMixedDragUsesWindow,
  getResizingShape,
  getPenPanel,
  getEraserPanel,
  assignCanvasElements,
  setCtx,
  setLinkPreviewPoint,
  setStageResizeObserver,
  boardPersistenceApi,
  boardShellApi,
  boardUiSetupApi,
  boardSelectionQueryApi,
  boardSelectionStateApi,
  boardLinkPopupApi,
  boardToolbarPopupApi,
  boardCanvasQueryApi,
  boardCanvasRenderApi,
  boardShapeResizeApi,
  boardShapeEditorApi,
  boardLinkEditorApi,
  boardLifecycleApi,
  boardViewportApi,
  boardCursorApi,
  boardLinkInteractionApi,
  boardShapeEraserApi,
  boardShapeRendererApi,
  boardLinkRenderApi,
  boardItemToolbarShellApi,
  inkTools,
  shapeTools,
  getConstrainedPoint,
  makeLinkEndpoint,
  linkTypeShape,
  toolDraw,
  toolErase,
  toolHand,
  toolLine,
  toolLink,
  toolSelect,
  stageResizeObserverCtor,
  zoomStep,
}) {
  const boardHotkeys = createBoardHotkeysController({
    documentRef,
    getCurrentTool,
    getSingleSelectedShape: boardSelectionQueryApi.getSingleSelectedShape,
    getTargetToolSelect: () => toolSelect,
    isBoardTabActive: () =>
      documentRef.getElementById("boardTab")?.classList.contains("active"),
    deleteSelectedShape: boardSelectionStateApi.deleteSelectedShape,
    redoBoard: boardShellApi.redoBoard,
    selectAllElements: boardSelectionStateApi.selectAllElements,
    setTool: boardShellApi.setTool,
    startShapeTextEditing: boardShapeEditorApi.startShapeTextEditing,
    undoBoard: boardShellApi.undoBoard,
  });

  const boardCanvasPointer = createBoardCanvasPointerController({
    blurActiveBoardEditors: boardHotkeys.blurActiveBoardEditors,
    clearLinkPopup: boardLinkPopupApi.clearLinkPopup,
    clearLinkSelection: boardLinkInteractionApi.clearLinkSelection,
    closeEraserPanel: boardToolbarPopupApi.closeEraserPanel,
    closePenPanel: boardToolbarPopupApi.closePenPanel,
    commitShapeTextEditing: boardShapeEditorApi.commitShapeTextEditing,
    createId,
    drawStroke: boardShapeRendererApi.drawStroke,
    drawStrokeSegment: boardShapeRendererApi.drawStrokeSegment,
    findLineTextAtPoint: boardCanvasQueryApi.findLineTextAtPoint,
    findLinkTextAtPoint: boardCanvasQueryApi.findLinkTextAtPoint,
    findLinkableShapeAtPoint: boardCanvasQueryApi.findLinkableShapeAtPoint,
    findShapeAtPoint: boardCanvasQueryApi.findShapeAtPoint,
    finishBoardPan: boardViewportApi.finishBoardPan,
    finishMarqueeSelection: boardSelectionStateApi.finishMarqueeSelection,
    finishMixedDrag: boardSelectionStateApi.finishMixedDrag,
    finishShapeDrag: boardSelectionStateApi.finishShapeDrag,
    finishShapeResize: boardShapeResizeApi.finishShapeResize,
    getActiveShape,
    getActiveStroke,
    getBoardSettings,
    getBoardStrokes,
    getCanvas,
    getCanvasPoint: boardViewportApi.getCanvasPoint,
    getConstrainedPoint,
    getCtx,
    getCurrentTool,
    getDraggingMixed,
    getDraggingShape,
    getDrawing,
    getIsMarqueeSelecting,
    getMixedDragUsesWindow,
    getResizingShape,
    getSelectedItemIds,
    getSelectedShapeIds,
    getSelectedShapeTargets: boardSelectionQueryApi.getSelectedShapeTargets,
    getShapeEditingId,
    getShapeResizeHandleAtPoint: boardShapeResizeApi.getShapeResizeHandleAtPoint,
    getSingleSelectedShape: boardSelectionQueryApi.getSingleSelectedShape,
    getStage,
    handleLinkSelection: boardLinkInteractionApi.handleLinkSelection,
    inkTools,
    isBoardPanning: boardViewportApi.isBoardPanning,
    isEraserPanelOpen: () => Boolean(getEraserPanel()?.classList.contains("is-open")),
    isLinkingModeActive: boardLinkInteractionApi.isLinkingModeActive,
    isPenPanelOpen: () => Boolean(getPenPanel()?.classList.contains("is-open")),
    isShapeSelected: boardSelectionQueryApi.isShapeSelected,
    isShapeVisible: boardCanvasQueryApi.isShapeVisible,
    linkTypeShape,
    makeLinkEndpoint,
    moveMixedDrag: boardSelectionStateApi.moveMixedDrag,
    moveSelectedShape: boardSelectionStateApi.moveSelectedShape,
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    removeShapesByEraser: boardShapeEraserApi.removeShapesByEraser,
    scheduleSave: boardPersistenceApi.scheduleSave,
    selectLink: boardLinkPopupApi.selectLink,
    selectShape: boardSelectionStateApi.selectShape,
    setActiveShape,
    setActiveStroke,
    setDrawing,
    setTool: boardShellApi.setTool,
    shapeTools,
    startBoardPan: boardViewportApi.startBoardPan,
    startLinkTextEditing: boardLinkEditorApi.startLinkTextEditing,
    startMarqueeSelection: boardSelectionStateApi.startMarqueeSelection,
    startMixedDrag: boardSelectionStateApi.startMixedDrag,
    startShapeDrag: boardSelectionStateApi.startShapeDrag,
    startShapeResize: boardShapeResizeApi.startShapeResize,
    startShapeTextEditing: boardShapeEditorApi.startShapeTextEditing,
    toggleShapeSelection: boardSelectionStateApi.toggleShapeSelection,
    toolDraw,
    toolErase,
    toolHand,
    toolLine,
    toolSelect,
    updateBoardPan: boardViewportApi.updateBoardPan,
    updateEraserCursor: boardCursorApi.updateEraserCursor,
    updateEraserCursorSize: boardCursorApi.updateEraserCursorSize,
    updateEmptyState: boardLifecycleApi.updateEmptyState,
    updateMarqueeSelection: boardSelectionStateApi.updateMarqueeSelection,
    updatePenCursor: boardCursorApi.updatePenCursor,
    updateShapeResize: boardShapeResizeApi.updateShapeResize,
    updateShapeResizeHover: boardShapeResizeApi.updateShapeResizeHover,
  });

  const boardCanvasBootstrap = createBoardCanvasBootstrapController({
    assignCanvasElements,
    blurActiveBoardEditors: boardHotkeys.blurActiveBoardEditors,
    clearLinkHoverTarget: boardLinkInteractionApi.clearLinkHoverTarget,
    clearLinkPreviewLine: boardLinkRenderApi.clearLinkPreviewLine,
    clearLinkSelection: boardLinkInteractionApi.clearLinkSelection,
    closeZoomPanel: boardUiSetupApi.closeZoomPanel,
    documentRef,
    finishLinkDrag: boardLinkInteractionApi.finishLinkDrag,
    getBoardZoom: boardViewportApi.getBoardZoom,
    getCurrentTool,
    getLinkEndpointFromEvent: boardLinkInteractionApi.getLinkEndpointFromEvent,
    getLinksSvg,
    getStage,
    getText,
    getWorldPointFromClient: boardViewportApi.getWorldPointFromClient,
    handleCanvasContextMenu: (...args) =>
      getViewportController().handleCanvasContextMenu(...args),
    handleStageContextMenu: (...args) =>
      getViewportController().handleStageContextMenu(...args),
    hideEraserCursor: boardCursorApi.hideEraserCursor,
    hideItemToolbar: boardItemToolbarShellApi.hideItemToolbar,
    hidePenCursor: boardCursorApi.hidePenCursor,
    isBoardPanning: boardViewportApi.isBoardPanning,
    isLinkingModeActive: boardLinkInteractionApi.isLinkingModeActive,
    linkTool: toolLink,
    onCanvasDoubleClick: boardCanvasPointer.onCanvasDoubleClick,
    onCanvasPointerDown: boardCanvasPointer.onCanvasPointerDown,
    onCanvasPointerMove: boardCanvasPointer.onCanvasPointerMove,
    onCanvasPointerUp: boardCanvasPointer.onCanvasPointerUp,
    onStageGestureChange: boardViewportApi.onStageGestureChange,
    onStageGestureEnd: boardViewportApi.onStageGestureEnd,
    onStageGestureStart: boardViewportApi.onStageGestureStart,
    onStageWheel: boardViewportApi.onStageWheel,
    resizeCanvas: boardViewportApi.resizeCanvas,
    setBoardZoom: boardViewportApi.setBoardZoom,
    setCtx,
    setLinkPreviewPoint,
    setStageResizeObserver,
    setupZoomPanel: boardUiSetupApi.setupZoomPanel,
    showEraserCursor: boardCursorApi.showEraserCursor,
    showPenCursor: boardCursorApi.showPenCursor,
    stageResizeObserverCtor,
    toolDraw,
    toolErase,
    toolHand,
    updateEraserCursor: boardCursorApi.updateEraserCursor,
    updateLinkHoverTarget: boardLinkInteractionApi.updateLinkHoverTarget,
    updateLinkPreviewFromState: boardLinkRenderApi.updateLinkPreviewFromState,
    updatePenCursor: boardCursorApi.updatePenCursor,
    updateViewportTransform: boardViewportApi.updateViewportTransform,
    windowRef,
    zoomStep,
  });

  return {
    boardCanvasBootstrap,
    boardCanvasPointer,
    boardHotkeys,
  };
}
