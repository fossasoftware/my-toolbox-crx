import { colorsMatch } from "./board-color-utils.js";
import { createBoardItemContentController } from "./board-item-content-controller.js";
import { createBoardItemInteractionController } from "./board-item-interaction-controller.js";
import { createBoardItemLifecycleController } from "./board-item-lifecycle-controller.js";
import { createBoardItemRenameController } from "./board-item-menu-controller.js";
import { createBoardItemMenuShellController } from "./board-item-menu-shell-controller.js";
import { createBoardItemRenderer } from "./board-item-renderer.js";
import { createBoardItemStyleController } from "./board-item-style-controller.js";
import {
  setupItemColorPicker,
  setupItemSizePicker,
} from "./board-item-toolbar-setup.js";
import { createBoardItemToolbarShellController } from "./board-item-toolbar-shell-controller.js";

export function createBoardItemStack({
  documentRef,
  windowRef,
  getText,
  createId,
  itemElements,
  itemToolbars,
  getBoardItems,
  getBoardLinks,
  getBoardSettings,
  getStage,
  getItemsContainer,
  getItemMenu,
  getItemControls,
  getCurrentTool,
  getActiveItemToolbarId,
  setActiveItemToolbarId,
  getItemMenuTargetId,
  setItemMenuTargetId,
  getResizeObserver,
  setResizeObserver,
  getItemOffset,
  setItemOffset,
  getSelectedItemIds,
  getSelectedShapeIds,
  getLinkSource,
  getLinkHoverTarget,
  getDraggingMixed,
  getResizingItem,
  setResizingItem,
  getMixedDragUsesWindow,
  setMixedDragUsesWindow,
  getItemMenuColorButtons,
  getItemMenuTextColorButtons,
  getItemMenuTextSizeButtons,
  setBoardItems,
  setBoardLinks,
  boardShellApi,
  boardPersistenceApi,
  boardViewportApi,
  boardSelectionStateApi,
  boardLinkInteractionApi,
  boardLinkHighlightApi,
  boardLinkRenderApi,
  boardCanvasRenderApi,
  boardLifecycleApi,
  boardUiPreview,
  itemDefaults,
  itemMenuOffset,
  itemOffsetLimit,
  itemOffsetStep,
  itemTypeColors,
  textColorPresets,
  textSizePresets,
  linkTypeItem,
  toolSelect,
  linkHasEndpoint,
  makeLinkEndpoint,
}) {
  const boardItemContent = createBoardItemContentController({
    getDefaultTextColor: () => getBoardSettings().textColor,
    getDefaultTextSize: () => getBoardSettings().textSize,
    getText,
    itemElements,
    itemTypeColors,
  });

  const boardItemStyle = createBoardItemStyleController({
    colorsMatch,
    getItemColorKey: boardItemContent.getItemColorKey,
    getItemTextColor: boardItemContent.getItemTextColor,
    getItemTextSize: boardItemContent.getItemTextSize,
    getItemTitle: boardItemContent.getItemTitle,
    getRefs: () => ({
      itemElements,
      itemMenuColorButtons: getItemMenuColorButtons(),
      itemMenuTextColorButtons: getItemMenuTextColorButtons(),
      itemMenuTextSizeButtons: getItemMenuTextSizeButtons(),
      itemToolbars,
    }),
    itemTypeColors,
    scheduleHistoryCommit: boardShellApi.scheduleHistoryCommit,
    scheduleSave: boardPersistenceApi.scheduleSave,
    setShapeColorButtonSwatch: boardUiPreview.setShapeColorButtonSwatch,
    syncShapeColorMenu: boardUiPreview.syncShapeColorMenu,
    syncShapeSizeMenu: boardUiPreview.syncShapeSizeMenu,
    textSizePresets,
    updateItemTextStyles: boardItemContent.updateItemTextStyles,
    updateItemTitleElement: boardItemContent.updateItemTitleElement,
    applyItemColorStyles: boardItemContent.applyItemColorStyles,
  });

  const boardItemRename = createBoardItemRenameController({
    itemElements,
    getItemDisplayTitle: boardItemContent.getItemDisplayTitle,
    updateItemTitleElement: boardItemContent.updateItemTitleElement,
    scheduleHistoryCommit: boardShellApi.scheduleHistoryCommit,
    scheduleSave: boardPersistenceApi.scheduleSave,
  });

  const boardItemMenuShell = createBoardItemMenuShellController({
    getBoardItems,
    getItemMenu,
    getStage,
    getTargetId: getItemMenuTargetId,
    itemMenuOffset,
    setTargetId: setItemMenuTargetId,
    syncItemMenuSelection: boardItemStyle.syncItemMenuSelection,
    syncItemMenuTextOptions: boardItemStyle.syncItemMenuTextOptions,
  });

  const boardItemToolbarShell = createBoardItemToolbarShellController({
    documentRef,
    getActiveItemToolbarId,
    getBoardItems,
    getItemControls,
    getItemToolbars: () => itemToolbars,
    getStage,
    getViewPan: boardViewportApi.getViewPan,
    getZoom: boardViewportApi.getBoardZoom,
    setActiveItemToolbarId,
    syncItemToolbar: boardItemStyle.syncItemToolbar,
  });

  const boardItemInteraction = createBoardItemInteractionController({
    getActiveItemToolbarId,
    getBoardItems,
    getBoardZoom: boardViewportApi.getBoardZoom,
    getDraggingMixed,
    getItemElements: () => itemElements,
    getLinkHoverTarget,
    getLinkSource,
    getResizingItem,
    getSelectedItemIds,
    getSelectedShapeIds,
    getWorldPointFromClient: boardViewportApi.getWorldPointFromClient,
    linkTypeItem,
    finishMixedDrag: boardSelectionStateApi.finishMixedDrag,
    moveMixedDrag: boardSelectionStateApi.moveMixedDrag,
    positionItemToolbar: boardItemToolbarShell.positionItemToolbar,
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    scheduleItemToolbarUpdate: boardItemToolbarShell.scheduleItemToolbarUpdate,
    scheduleLinkUpdate: boardLinkRenderApi.scheduleLinkUpdate,
    scheduleSave: boardPersistenceApi.scheduleSave,
    setMixedDragUsesWindow,
    setResizingItem,
    startMixedDrag: boardSelectionStateApi.startMixedDrag,
    syncItemSelectionElement: boardSelectionStateApi.syncItemSelectionElement,
    updateLinkItemHighlight: boardLinkHighlightApi.updateLinkItemHighlight,
    windowRef,
  });

  let boardItemRenderer;
  const boardItemLifecycle = createBoardItemLifecycleController({
    createId,
    getActiveItemToolbarId,
    getBoardItems,
    getBoardLinks,
    getBoardZoom: boardViewportApi.getBoardZoom,
    getDefaultTextColor: () => getBoardSettings().textColor,
    getDefaultTextSize: () => getBoardSettings().textSize,
    getItemMenuTargetId,
    getItemOffset,
    getItemToolbars: () => itemToolbars,
    getLinkSource,
    getSelectedItemIds,
    getStage,
    getViewPan: boardViewportApi.getViewPan,
    hideItemToolbar: boardItemToolbarShell.hideItemToolbar,
    focusItemBody: boardItemContent.focusItemBody,
    itemDefaults,
    itemOffsetLimit,
    itemOffsetStep,
    linkHasEndpoint,
    linkTypeItem,
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    renderItems: (...args) => boardItemRenderer.renderItems(...args),
    scheduleSave: boardPersistenceApi.scheduleSave,
    setActiveItemToolbarId,
    setBoardItems,
    setBoardLinks,
    setItemOffset,
    setTool: boardShellApi.setTool,
    toolSelect,
    updateEmptyState: boardLifecycleApi.updateEmptyState,
    updateItemSelectionStyles: boardSelectionStateApi.updateItemSelectionStyles,
    clearLinkSelection: boardLinkInteractionApi.clearLinkSelection,
    closeItemMenu: boardItemMenuShell.closeItemMenu,
  });

  boardItemRenderer = createBoardItemRenderer({
    applyItemColorStyles: boardItemContent.applyItemColorStyles,
    applyItemTextColorChoice: boardItemStyle.applyItemTextColorChoice,
    applyItemTextSizeChoice: boardItemStyle.applyItemTextSizeChoice,
    applyTextStylesToBody: boardItemContent.applyTextStylesToBody,
    closeItemToolbarMenus: boardItemToolbarShell.closeItemToolbarMenus,
    documentRef,
    getActiveItemToolbarId,
    getCurrentTool,
    getDefaultTextColor: () => getBoardSettings().textColor,
    getDefaultTextSize: () => getBoardSettings().textSize,
    getItemControls,
    getItemDisplayTitle: boardItemContent.getItemDisplayTitle,
    getItemElements: () => itemElements,
    getItemMenu,
    getItemToolbars: () => itemToolbars,
    getItems: getBoardItems,
    getItemsContainer,
    getResizeObserver,
    getSelectedItemIds,
    getSelectedShapeIds,
    getText,
    handleLinkSelection: boardLinkInteractionApi.handleLinkSelection,
    hasRichTextFormatting: boardItemContent.hasRichTextFormatting,
    hideItemToolbar: boardItemToolbarShell.hideItemToolbar,
    isLinkingModeActive: boardLinkInteractionApi.isLinkingModeActive,
    itemDefaults,
    linkTypeItem,
    makeLinkEndpoint,
    normalizeInlineTextDecorations:
      boardItemContent.normalizeInlineTextDecorations,
    openItemMenu: boardItemMenuShell.openItemMenu,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    removeItem: boardItemLifecycle.removeItem,
    resizeObserverCtor: ResizeObserver,
    scheduleHistoryCommit: boardShellApi.scheduleHistoryCommit,
    scheduleItemToolbarUpdate: boardItemToolbarShell.scheduleItemToolbarUpdate,
    scheduleLinkUpdate: boardLinkRenderApi.scheduleLinkUpdate,
    scheduleSave: boardPersistenceApi.scheduleSave,
    setActiveItemToolbarId,
    setResizeObserver,
    setupItemColorPicker,
    setupItemSizePicker,
    showItemToolbar: boardItemToolbarShell.showItemToolbar,
    startLinkFromToolbar: boardLinkInteractionApi.startLinkFromToolbar,
    startDrag: (event, id) => boardItemInteraction.startDrag(event, id),
    startItemResize: boardItemInteraction.startItemResize,
    syncItemSelectionElement: boardSelectionStateApi.syncItemSelectionElement,
    syncItemToolbar: boardItemStyle.syncItemToolbar,
    syncItemToolbarDuringTransition:
      boardItemToolbarShell.syncItemToolbarDuringTransition,
    textColorPresets,
    textSizePresets,
    toggleItemSelection: boardSelectionStateApi.toggleItemSelection,
    toolSelect,
    updateItemSelectionStyles: boardSelectionStateApi.updateItemSelectionStyles,
    updateLinks: boardLinkRenderApi.updateLinks,
  });

  return {
    boardItemContent,
    boardItemInteraction,
    boardItemLifecycle,
    boardItemMenuShell,
    boardItemRename,
    boardItemRenderer,
    boardItemStyle,
    boardItemToolbarShell,
  };
}
