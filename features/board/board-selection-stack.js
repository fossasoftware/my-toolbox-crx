import { createBoardSelectionOverlayController } from "./board-selection-overlay-controller.js";
import { createBoardSelectionQueryController } from "./board-selection-query-controller.js";
import { createBoardSelectionStateController } from "./board-selection-state-controller.js";

export function createBoardSelectionStack({
  documentRef,
  getBoardItems,
  setBoardItems,
  getBoardLinks,
  setBoardLinks,
  getBoardStrokes,
  setBoardStrokes,
  getSelectedItemIds,
  setSelectedItemIds,
  getSelectedShapeIds,
  setSelectedShapeIds,
  getItemElements,
  getItemSelectionElements,
  getItemSelectionLayer,
  getItemMenuTargetId,
  getLinkSource,
  getDraggingMixed,
  setDraggingMixed,
  getDraggingShape,
  setDraggingShape,
  getIsMarqueeSelecting,
  setIsMarqueeSelecting,
  getMarqueeAdditive,
  setMarqueeAdditive,
  getMarqueeBaseItemSelection,
  setMarqueeBaseItemSelection,
  getMarqueeBaseSelection,
  setMarqueeBaseSelection,
  getMarqueeRect,
  setMarqueeRect,
  getMarqueeStart,
  setMarqueeStart,
  getMixedDragItemElements,
  setMixedDragItemElements,
  getMixedDragItemSnapshot,
  setMixedDragItemSnapshot,
  getMixedDragShapeSnapshot,
  setMixedDragShapeSnapshot,
  getMixedDragStart,
  setMixedDragStart,
  setMixedDragUsesWindow,
  getResizingShape,
  setResizingShape,
  getShapeEditingId,
  getShapeSelectionFromShift,
  setShapeSelectionFromShift,
  getShapeToolbarPinned,
  setShapeToolbarPinned,
  getShapeDragSnapshot,
  setShapeDragSnapshot,
  getShapeDragStart,
  setShapeDragStart,
  setShapeResizeHandle,
  setShapeResizeHover,
  setShapeResizeId,
  setShapeResizeSnapshot,
  getCurrentTool,
  getCtx,
  getBoardZoom,
  getLinkHoverTarget,
  getShapeById,
  getSelectionRect,
  getLinkType,
  getShapeHitPadding,
  isSelectableStroke,
  boardShellApi,
  boardPersistenceApi,
  boardCanvasRenderApi,
  boardItemRenderApi,
  boardLinkRenderApi,
  boardLifecycleApi,
  boardItemInteractionApi,
  boardItemMenuShellApi,
  boardShapeEditorApi,
  boardLinkInteractionApi,
  boardShapeResizeApi,
  boardSelectionVisualApi,
  itemSelectionOutset,
  linkTypeItem,
  linkTypeShape,
  selectionDash,
  selectionRadius,
  toolSelect,
}) {
  let boardSelectionState;

  const boardSelectionQuery = createBoardSelectionQueryController({
    getBoardItems,
    getBoardStrokes,
    getSelectedItemIds,
    getSelectedShapeIds,
    getShapeHitPadding,
    isSelectableStroke,
    setSelectedItemIds,
    setSelectedShapeIds,
    updateItemSelectionStyles: (...args) =>
      boardSelectionState.updateItemSelectionStyles(...args),
  });

  boardSelectionState = createBoardSelectionStateController({
    documentRef,
    getBoardItems,
    getBoardLinks,
    getBoardStrokes,
    getDraggingMixed,
    getDraggingShape,
    getIsMarqueeSelecting,
    getItemElements,
    getItemMenuTargetId,
    getItemSelectionElements,
    getItemSelectionLayer,
    getLinkSource,
    getMarqueeAdditive,
    getMarqueeBaseItemSelection,
    getMarqueeBaseSelection,
    getMarqueeRect,
    getMarqueeStart,
    getMixedDragItemElements,
    getMixedDragItemSnapshot,
    getMixedDragShapeSnapshot,
    getMixedDragStart,
    getResizingShape,
    getSelectedItems: (...args) => boardSelectionQuery.getSelectedItems(...args),
    getSelectedItemIds,
    getSelectedShapes: (...args) => boardSelectionQuery.getSelectedShapes(...args),
    getSelectedShapeIds,
    getShapeById,
    getShapeEditingId,
    getShapeSelectionFromShift,
    getShapeToolbarPinned,
    getShapeDragSnapshot,
    getShapeDragStart,
    getSelectableItemIdsInRect: (...args) =>
      boardSelectionQuery.getSelectableItemIdsInRect(...args),
    getSelectableStrokeIdsInRect: (...args) =>
      boardSelectionQuery.getSelectableStrokeIdsInRect(...args),
    getSelectionRect,
    getLinkType,
    itemSelectionOutset,
    linkTypeItem,
    linkTypeShape,
    pushHistorySnapshot: boardShellApi.pushHistorySnapshot,
    redrawCanvas: boardCanvasRenderApi.redrawCanvas,
    renderItems: boardItemRenderApi.renderItems,
    scheduleLinkUpdate: boardLinkRenderApi.scheduleLinkUpdate,
    scheduleSave: boardPersistenceApi.scheduleSave,
    setBoardItems,
    setBoardLinks,
    setBoardStrokes,
    setDraggingMixed,
    setDraggingShape,
    setIsMarqueeSelecting,
    setMarqueeAdditive,
    setMarqueeBaseItemSelection,
    setMarqueeBaseSelection,
    setMarqueeRect,
    setMarqueeStart,
    setMixedDragItemElements,
    setMixedDragItemSnapshot,
    setMixedDragShapeSnapshot,
    setMixedDragStart,
    setMixedDragUsesWindow,
    setResizingShape,
    setSelectedItemIds,
    setSelectedShapeIds,
    setShapeDragSnapshot,
    setShapeDragStart,
    setShapeResizeHandle,
    setShapeResizeHover,
    setShapeResizeId,
    setShapeResizeSnapshot,
    setShapeSelectionFromShift,
    setShapeToolbarPinned,
    selectionRadius,
    updateEmptyState: boardLifecycleApi.updateEmptyState,
    updateItemPosition: boardItemInteractionApi.updateItemPosition,
    closeItemMenu: boardItemMenuShellApi.closeItemMenu,
    closeShapeEditor: boardShapeEditorApi.closeShapeEditor,
    clearLinkSelection: boardLinkInteractionApi.clearLinkSelection,
    isSelectableStroke,
  });

  const boardSelectionOverlay = createBoardSelectionOverlayController({
    drawShapeResizeHandles: boardShapeResizeApi.drawShapeResizeHandles,
    getBoardStrokes,
    getBoardZoom,
    getCtx,
    getCurrentTool,
    getIsMarqueeSelecting,
    getLinkHoverTarget,
    getLinkSelectionColor: boardSelectionVisualApi.getLinkSelectionColor,
    getLinkSource,
    getMarqueeRect,
    getSelectedShapeIds,
    getSelectedShapes: (...args) => boardSelectionQuery.getSelectedShapes(...args),
    getSelectionBounds: boardSelectionVisualApi.getSelectionBounds,
    getSelectionColor: boardSelectionVisualApi.getSelectionColor,
    getSelectionFillColor: boardSelectionVisualApi.getSelectionFillColor,
    getShapeSelectionBounds: boardSelectionVisualApi.getShapeSelectionBounds,
    linkTypeShape,
    selectionDash,
    selectionRadius,
    shouldDrawShapeSelection: (...args) =>
      boardSelectionState.shouldDrawShapeSelection(...args),
    toolSelect,
  });

  return {
    boardSelectionOverlay,
    boardSelectionQuery,
    boardSelectionState,
  };
}
